_BY_KEY = {t.key: t for t in TERMS}


def explain(*texts: str) -> list[dict]:
    """서류 문구에서 알아볼 만한 용어를 찾아 쉬운 말로 돌려준다.

    한 계열에서 하나만 뽑는다. '임대차'와 '임차'가 같이 걸려 같은 설명이
    두 번 나오면 읽는 사람만 헷갈린다.
    """
    haystack = " ".join(t for t in texts if t)
    if not haystack:
        return []

    found: list[dict] = []
    for term in TERMS:
        if any(n in haystack for n in term.needles):
            found.append({
                "term": term.term,
                "plain": term.plain,
                "impact": term.impact,
                "law": term.law,
            })
    return found


def explain_keys(keys: list[str]) -> list[dict]:
    """키로 직접 뽑는다. 지목처럼 문구가 아니라 값으로 판정되는 것들."""
    out = []
    for k in keys:
        t = _BY_KEY.get(k)
        if t:
            out.append({"term": t.term, "plain": t.plain,
                        "impact": t.impact, "law": t.law})
    return out
