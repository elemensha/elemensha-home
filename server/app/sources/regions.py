def is_regulated(sgg_code: str) -> bool:
    """시군구 코드가 규제지역인지."""
    return sgg_code in REGULATED_SGG_CODES


def regulated_since(sgg_code: str) -> str | None:
    return REGULATED_SGG_CODES.get(sgg_code)


def regulated_names() -> list[str]:
    return sorted(name_of(code) for code in REGULATED_SGG_CODES)
