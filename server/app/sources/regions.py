ALL: dict[str, str] = {**SEOUL, **GYEONGGI, **INCHEON}


def codes_for(sido_names: list[str]) -> list[str]:
    """시도 이름 목록으로 해당하는 시군구 코드를 모은다."""
    if not sido_names:
        return list(ALL)
    return [code for code, name in ALL.items() if any(s in name for s in sido_names)]


def name_of(code: str) -> str:
    return ALL.get(code, code)


