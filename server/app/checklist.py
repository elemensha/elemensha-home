def _kind_name(listing: dict, detail: dict) -> str:
    """이 물건이 어떤 공매인지. 신탁은 재산유형에 안 나와서 따로 찾는다."""
    raw = listing.get("raw") or {}
    div = str(raw.get("prptDivNm") or "")
    org = str(detail.get("delegating_org") or "")
    if "신탁" in org or "신탁" in str(listing.get("title") or ""):
        return "신탁재산"
    for name in ("압류재산", "국유재산", "공유재산"):
        if name in div:
            return name
    # 기타일반재산은 위임기관에 따라 성격이 갈려 단정하지 않는다.
    return ""


def sale_kind(listing: dict, detail: dict | None = None) -> dict:
    """이 물건이 어떤 종류의 공매인지와, 그래서 뭘 조심해야 하는지."""
    name = _kind_name(listing, detail or {})
    if not name:
        return {}
    return {"kind": name, **SALE_KINDS[name]}


def build(listing: dict, detail: dict | None = None) -> list[dict]:
    """이 물건에 필요한 점검만 순서대로 돌려준다."""
    detail = detail or {}
    raw = listing.get("raw") or {}
    text = " ".join(str(x) for x in (
        detail.get("notes", ""), detail.get("usage_status", ""),
        listing.get("title", ""), raw.get("usage", ""),
    ))

    is_land = listing.get("property_type") == "토지"
    kind = _kind_name(listing, detail)
    steps = list(BASE)

    if kind == "신탁재산":
        # 신탁원부가 등기부 다음으로 온다 - 등기부에서 신탁등기를 본 뒤에
        # 신청하는 것이라 순서가 뒤집히면 안 된다.
        steps = [steps[0], TRUST[0]] + steps[1:] + [TRUST[1]]

    # 토지에 전입세대확인서를 떼러 가는 것은 헛걸음이다.
    if is_land and "점유" not in text and "임차" not in text:
        steps = [s for s in steps if "전입세대" not in s.title]

    if is_land:
        steps += LAND
        if raw.get("needs_farmland_permit") or raw.get("usage_minor") in ("전", "답", "과수원"):
            steps = FARMLAND + steps   # 이건 입찰 전에 해야 해서 맨 앞이다

    return [
        {"step": i, "title": s.title, "why": s.why, "how": s.how,
         "judge": s.judge, "cost": s.cost}
        for i, s in enumerate(steps, 1)
    ]
